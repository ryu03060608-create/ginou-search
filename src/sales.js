// ※ すべて一般的な目安です。実際の可否・人数・要件は
//   監理団体／地方出入国在留管理局／JITCO等で必ず確認してください。
// ============================================================

// ------------------------------------------------------------
// 受入れ人数枠（団体監理型・第1号・1年間の「基本人数枠」の目安）
//   常勤職員数に応じて決まる。優良認定・2号含む全体では拡大する。
// ------------------------------------------------------------
export function computeQuota(staff) {
  const n = Number(staff)
  if (!n || n < 1) return null
  let base
  if (n >= 301) base = Math.floor(n / 20)
  else if (n >= 201) base = 15
  else if (n >= 101) base = 10
  else if (n >= 51) base = 6
  else if (n >= 41) base = 5
  else if (n >= 31) base = 4
  else base = 3 // 30人以下
  return {
    base, // 第1号・1年あたりの基本人数枠
    withNiGou: base * 3, // 1号+2号(2年)を満了まで在籍させた場合の在籍上限の目安
    yuryo: base * 2, // 優良認定時の第1号・1年あたり
  }
}

