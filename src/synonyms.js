// 入力語を「検索トークンの配列」に展開する
export function expandTokens(raw) {
  const term = (raw || '').trim().toLowerCase()
  if (!term) return []
  const tokens = new Set()
  // スペースや読点で区切って複数キーワードにも対応
  const words = term.split(/[\s,、，・]+/).filter(Boolean)
  words.forEach((w) => tokens.add(w))
  tokens.add(term)
  const inputs = [term, ...words]
  for (const [key, targets] of Object.entries(SYNONYMS)) {
    const k = key.toLowerCase()
    const hit = inputs.some((w) => w.includes(k) || (k.includes(w) && w.length >= 2))
    if (hit) targets.forEach((t) => tokens.add(t.toLowerCase()))
  }
  return [...tokens]
}

// 1行（職種）がトークン群のいずれかにマッチするか
export function rowMatches(row, tokens) {
  if (!tokens.length) return true
  const hay = (row.field + ' ' + row.job + ' ' + row.tasks.join(' ')).toLowerCase()
  return tokens.some((t) => hay.includes(t))
}
